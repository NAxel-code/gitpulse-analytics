"use client";

import { useState, useMemo } from "react";
import {
  X,
  Copy,
  Check,
  Download,
  Share2,
  FileText,
  Sparkles,
  MessageSquare,
  FileCode,
  Table,
} from "lucide-react";
import { ContributorItem, isBotAccount } from "./ContributorTable";

interface SprintExportModalProps {
  isOpen: boolean;
  onClose: () => void;
  repoName: string;
  days: number;
  kpiData: any;
  contributors: ContributorItem[];
  executiveSummary: any;
}

export function SprintExportModal({
  isOpen,
  onClose,
  repoName,
  days,
  kpiData,
  contributors,
  executiveSummary,
}: SprintExportModalProps) {
  const [activeTab, setActiveTab] = useState<"slack" | "markdown" | "csv">("slack");
  const [copied, setCopied] = useState(false);
  const [excludeBots, setExcludeBots] = useState(true);

  // Compute stats
  const humanContribs = useMemo(() => {
    return (contributors || []).filter((c) => (excludeBots ? !isBotAccount(c.login) : true));
  }, [contributors, excludeBots]);

  const totalCommits = kpiData?.total_commits || 0;
  const activeDevsCount = kpiData?.active_contributors || humanContribs.length || 0;
  const prMergeRate = kpiData?.pr_merge_rate != null ? Number(kpiData.pr_merge_rate).toFixed(1) : "0.0";
  const mergedPRs = kpiData?.merged_prs || 0;
  const totalPRs = kpiData?.total_prs || 0;
  const leadTime = kpiData?.lead_time_hours != null ? Number(kpiData.lead_time_hours).toFixed(1) : "-";
  const linesAdded = kpiData?.lines_added_total ? (kpiData.lines_added_total / 1000).toFixed(1) : "0.0";
  const linesDeleted = kpiData?.lines_deleted_total ? (kpiData.lines_deleted_total / 1000).toFixed(1) : "0.0";

  const prDist = kpiData?.pr_size_distribution || { small: 0, medium: 0, large: 0 };
  const totalDist = (prDist.small + prDist.medium + prDist.large) || 1;
  const smallPRPct = Math.round((prDist.small / totalDist) * 100);

  // Top 3 contributors
  const topDevs = useMemo(() => {
    return humanContribs.slice(0, 3).map((c) => `@${c.login}`).join(", ");
  }, [humanContribs]);

  // Bus factor
  const busFactor = useMemo(() => {
    const totalC = humanContribs.reduce((acc, c) => acc + (c.commits || 0), 0);
    let cumulative = 0;
    let count = 0;
    for (const c of humanContribs) {
      count++;
      cumulative += c.commits || 0;
      if (cumulative >= totalC * 0.65 || count >= 4) break;
    }
    return Math.max(1, count || 1);
  }, [humanContribs]);

  // Generate Slack Format
  const slackText = useMemo(() => {
    return [
      `🚀 *GitPulse Engineering Sprint Summary: ${repoName}*`,
      `⏱️ *Timeframe:* Last ${days} Days | 🛡️ *Bus Factor:* ${busFactor} Maintainers`,
      ``,
      `📊 *Key Delivery Metrics:*`,
      `• *Active Contributors:* ${activeDevsCount} devs${topDevs ? ` (Top: ${topDevs})` : ""}`,
      `• *PR Merge Velocity:* ${prMergeRate}% (${mergedPRs} of ${totalPRs} PRs merged)`,
      `• *Lead Time to Merge:* ${leadTime} hrs ${Number(leadTime) < 24 ? "⚡ (Elite)" : "⏱️"}`,
      `• *PR Size Hygiene:* ${smallPRPct}% Atomic (<200 LoC)`,
      `• *Net Code Churn:* +${linesAdded}k / -${linesDeleted}k LoC across ${totalCommits} commits`,
      ``,
      `💡 *Executive Insight:*`,
      `> ${executiveSummary?.executive_summary || "PR review pipeline operating normally with stable throughput."}`,
      ``,
      `🔗 _Generated by GitPulse Analytics_`,
    ].join("\n");
  }, [repoName, days, busFactor, activeDevsCount, topDevs, prMergeRate, mergedPRs, totalPRs, leadTime, smallPRPct, linesAdded, linesDeleted, totalCommits, executiveSummary]);

  // Generate Markdown Format
  const markdownText = useMemo(() => {
    return [
      `### 🚀 GitPulse Engineering Sprint Summary: \`${repoName}\``,
      `**Timeframe:** Last ${days} Days | **Bus Factor:** ${busFactor} Maintainers | **Monitored PRs:** ${totalPRs}`,
      ``,
      `#### 📊 Core Delivery Metrics`,
      `| Metric | Value | Status / Notes |`,
      `| :--- | :--- | :--- |`,
      `| **Active Contributors** | \`${activeDevsCount} devs\` | ${topDevs ? `Top: ${topDevs}` : "Active team"} |`,
      `| **PR Merge Velocity** | \`${prMergeRate}%\` | ${mergedPRs} merged out of ${totalPRs} PRs |`,
      `| **Lead Time to Merge** | \`${leadTime} hrs\` | ${Number(leadTime) < 24 ? "🏆 Elite Tier (<24h)" : "⏱️ Standard"} |`,
      `| **PR Size Hygiene** | \`${smallPRPct}% Small\` | Target <200 LoC for rapid code reviews |`,
      `| **Net Code Churn** | \`+${linesAdded}k / -${linesDeleted}k\` | ${totalCommits} commits pushed |`,
      ``,
      `#### 💡 Daily Engineering Brief`,
      `> ${executiveSummary?.executive_summary || "PR review pipeline operating normally with stable throughput."}`,
      ``,
      ...(executiveSummary?.key_takeaways || []).map((t: string) => `- ${t}`),
      ``,
      `---`,
      `*Report generated automatically by [GitPulse Analytics](https://github.com/NAxel-code/gitpulse-analytics).*`,
    ].join("\n");
  }, [repoName, days, busFactor, totalPRs, activeDevsCount, topDevs, prMergeRate, mergedPRs, leadTime, smallPRPct, linesAdded, linesDeleted, totalCommits, executiveSummary]);

  // Generate CSV Format
  const csvText = useMemo(() => {
    const headers = ["Rank", "Contributor", "Commits", "PRs_Merged", "Lines_Added", "Lines_Deleted", "Velocity_Score", "Is_Bot"];
    const rows = (contributors || []).map((c, i) => [
      i + 1,
      `"${c.login}"`,
      c.commits || 0,
      c.prs_merged || 0,
      c.lines_added || 0,
      c.lines_deleted || 0,
      c.velocity_score || 0,
      isBotAccount(c.login) ? "true" : "false",
    ]);
    return [headers.join(","), ...rows.map((r) => r.join(","))].join("\n");
  }, [contributors]);

  const activeContent = activeTab === "slack" ? slackText : activeTab === "markdown" ? markdownText : csvText;

  const handleCopy = async () => {
    try {
      await navigator.clipboard.writeText(activeContent);
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    } catch (e) {
      console.error("Clipboard copy failed:", e);
    }
  };

  const handleDownload = () => {
    const isCsv = activeTab === "csv";
    const filename = `gitpulse-${repoName.replace("/", "-")}-${days}d.${isCsv ? "csv" : "md"}`;
    const blob = new Blob([activeContent], { type: isCsv ? "text/csv;charset=utf-8;" : "text/markdown;charset=utf-8;" });
    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");
    link.href = url;
    link.setAttribute("download", filename);
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
  };

  if (!isOpen) return null;

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-zinc-950/80 backdrop-blur-sm animate-in fade-in duration-150">
      <div className="relative w-full max-w-2xl rounded-2xl border border-zinc-800 bg-zinc-900 shadow-2xl overflow-hidden flex flex-col max-h-[88vh]">
        {/* Header */}
        <div className="flex items-center justify-between px-6 py-4 border-b border-zinc-800">
          <div className="flex items-center gap-2.5">
            <div className="flex h-8 w-8 items-center justify-center rounded-lg bg-indigo-500/10 border border-indigo-500/30 text-indigo-400">
              <Share2 className="h-4 w-4" />
            </div>
            <div>
              <h2 className="text-sm font-semibold text-white">Share Sprint Brief &amp; Export</h2>
              <p className="text-xs text-zinc-400">
                Ready-to-paste report for <span className="font-mono text-zinc-300">{repoName}</span> ({days}D window)
              </p>
            </div>
          </div>
          <button
            onClick={onClose}
            className="rounded-lg p-1 text-zinc-400 hover:text-white hover:bg-zinc-800 transition"
          >
            <X className="h-4 w-4" />
          </button>
        </div>

        {/* Tab Selector & Controls */}
        <div className="px-6 py-3 border-b border-zinc-800/80 bg-zinc-950/50 flex flex-wrap items-center justify-between gap-3">
          <div className="flex items-center gap-1.5 p-1 rounded-xl bg-zinc-900 border border-zinc-800">
            <button
              onClick={() => setActiveTab("slack")}
              className={`flex items-center gap-1.5 rounded-lg px-3 py-1.5 text-xs font-medium transition cursor-pointer ${
                activeTab === "slack"
                  ? "bg-zinc-800 text-white font-semibold shadow-xs"
                  : "text-zinc-400 hover:text-zinc-200"
              }`}
            >
              <MessageSquare className="h-3.5 w-3.5 text-emerald-400" />
              <span>Slack &amp; Discord</span>
            </button>
            <button
              onClick={() => setActiveTab("markdown")}
              className={`flex items-center gap-1.5 rounded-lg px-3 py-1.5 text-xs font-medium transition cursor-pointer ${
                activeTab === "markdown"
                  ? "bg-zinc-800 text-white font-semibold shadow-xs"
                  : "text-zinc-400 hover:text-zinc-200"
              }`}
            >
              <FileCode className="h-3.5 w-3.5 text-indigo-400" />
              <span>GitHub / Markdown</span>
            </button>
            <button
              onClick={() => setActiveTab("csv")}
              className={`flex items-center gap-1.5 rounded-lg px-3 py-1.5 text-xs font-medium transition cursor-pointer ${
                activeTab === "csv"
                  ? "bg-zinc-800 text-white font-semibold shadow-xs"
                  : "text-zinc-400 hover:text-zinc-200"
              }`}
            >
              <Table className="h-3.5 w-3.5 text-amber-400" />
              <span>CSV Dataset</span>
            </button>
          </div>

          <label className="flex items-center gap-2 text-xs text-zinc-400 cursor-pointer select-none">
            <input
              type="checkbox"
              checked={excludeBots}
              onChange={(e) => setExcludeBots(e.target.checked)}
              className="rounded border-zinc-700 bg-zinc-800 text-indigo-500 focus:ring-indigo-400 focus:ring-offset-zinc-900"
            />
            <span>Filter Bot Accounts</span>
          </label>
        </div>

        {/* Content Preview */}
        <div className="p-6 overflow-y-auto flex-1 font-mono text-xs">
          <div className="relative rounded-xl border border-zinc-800 bg-zinc-950 p-4 text-zinc-300 leading-relaxed overflow-x-auto whitespace-pre-wrap selection:bg-indigo-500/30">
            {activeContent}
          </div>
        </div>

        {/* Footer Actions */}
        <div className="px-6 py-3.5 border-t border-zinc-800 bg-zinc-950/70 flex items-center justify-between gap-3">
          <div className="text-[11px] text-zinc-500">
            {activeTab === "csv" ? "Includes full contributor velocity metrics" : "Formatted with clean markdown syntax"}
          </div>
          <div className="flex items-center gap-2">
            <button
              onClick={handleDownload}
              className="flex items-center gap-1.5 rounded-xl border border-zinc-700 bg-zinc-800 px-3 py-1.5 text-xs font-medium text-zinc-200 hover:text-white hover:bg-zinc-750 transition cursor-pointer"
            >
              <Download className="h-3.5 w-3.5" />
              <span>Download {activeTab === "csv" ? ".csv" : ".md"}</span>
            </button>
            <button
              onClick={handleCopy}
              className={`flex items-center gap-1.5 rounded-xl px-4 py-1.5 text-xs font-semibold transition cursor-pointer ${
                copied
                  ? "bg-emerald-500 text-zinc-950 font-bold"
                  : "bg-indigo-600 text-white hover:bg-indigo-500 shadow-md shadow-indigo-600/20"
              }`}
            >
              {copied ? (
                <>
                  <Check className="h-3.5 w-3.5 stroke-[2.5]" />
                  <span>Copied to Clipboard!</span>
                </>
              ) : (
                <>
                  <Copy className="h-3.5 w-3.5" />
                  <span>Copy to Clipboard</span>
                </>
              )}
            </button>
          </div>
        </div>
      </div>
    </div>
  );
}
